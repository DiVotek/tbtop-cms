import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { join, relative, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import type { BetterAuthOptions } from "better-auth";
import { defaultAuthSchema } from "../betterAuth/defaultAuth";
import { BETTER_AUTH_MIGRATION, D1_AUTH, type D1MigrationOptions, d1Migrations } from "../db/d1Migrations";
import type { CliIo } from "./run";

const FILE = /^(\d+)_(.+)\.sql$/;

/**
 * Adds the missing migration files to `dir` (wrangler's `migrations_dir`,
 * default `migrations`), numbered after the last one there: each CMS
 * migration once, by name, and Better Auth's tables, or what its options
 * added since. Files already there are never rewritten. The paths written.
 */
export async function writeD1Migrations(dir: string, options: Omit<D1MigrationOptions, "applied"> = {}): Promise<string[]> {
	await mkdir(dir, { recursive: true });
	const existing = (await readdir(dir)).filter((file) => FILE.test(file)).sort();
	const names = new Set(existing.map((file) => (FILE.exec(file) as RegExpExecArray)[2] as string));
	const applied = await Promise.all(existing.map((file) => readFile(join(dir, file), "utf8")));
	let next = existing.reduce((max, file) => Math.max(max, Number((FILE.exec(file) as RegExpExecArray)[1])), 0) + 1;
	const authFiles = [...names].filter((name) => name === BETTER_AUTH_MIGRATION || name.startsWith(`${BETTER_AUTH_MIGRATION}_`)).length;

	const written: string[] = [];
	for (const file of await d1Migrations({ ...options, applied })) {
		const auth = file.name === BETTER_AUTH_MIGRATION;
		if (!auth && names.has(file.name)) {
			continue;
		}
		const name = auth && authFiles > 0 ? `${BETTER_AUTH_MIGRATION}_${authFiles + 1}` : file.name;
		const path = join(dir, `${String(next++).padStart(4, "0")}_${name}.sql`);
		await writeFile(path, `-- Generated by tbtop-cms d1:migrations. Apply with: wrangler d1 migrations apply <DB>\n\n${file.sql}`);
		written.push(path);
	}
	return written;
}

function flag(args: string[], name: string): string | undefined {
	const index = args.indexOf(`--${name}`);
	return index === -1 ? undefined : args[index + 1];
}

/** Better Auth's options from the Worker module `cloudflare(site, options)` returned; false: the Worker has none. */
async function authOfEntry(path: string): Promise<BetterAuthOptions | false> {
	const mod = (await import(pathToFileURL(resolve(path)).href)) as { default?: Record<symbol, unknown> };
	const auth = mod.default?.[D1_AUTH];
	if (auth === undefined) {
		throw new Error(`${path} must default-export cloudflare(site, options) from @tbtop/cms/cloudflare.`);
	}
	return auth as BetterAuthOptions | false;
}

/**
 * `tbtop-cms d1:migrations [--out migrations] [--entry worker.ts] [--locale en | --no-language]`:
 * the SQL files for `wrangler d1 migrations apply`. Without `--entry`,
 * Better Auth as `cloudflare(site)` builds it with no `auth` option.
 */
export async function runD1Migrations(args: string[], io: CliIo): Promise<number> {
	const out = flag(args, "out") ?? "migrations";
	const entry = flag(args, "entry");
	const locale = flag(args, "locale");
	const written = await writeD1Migrations(out, {
		auth: entry === undefined ? defaultAuthSchema() : await authOfEntry(entry),
		defaultLanguage: args.includes("--no-language") ? false : (locale ?? "en"),
	});
	for (const path of written) {
		io.out(`Wrote ${relative(process.cwd(), path)}`);
	}
	io.out(written.length === 0 ? `Nothing to add: ${out} is up to date.` : `\nApply on deploy: wrangler d1 migrations apply <DB> --remote`);
	return 0;
}
