<?php

declare(strict_types=1);

namespace Tbtop\Cms\BlockTypes;

use Illuminate\Support\Str;
use RuntimeException;
use Tbtop\Cms\Block\Block;

/**
 * Assembles registry.generated.ts next to blocks.generated.ts: the catalog
 * entry (zod props + editor description) and the React component for every
 * registered block, so the host spreads two objects into json-render's
 * defineCatalog()/defineRegistry() instead of maintaining the lists by hand.
 *
 * Components are found by convention, `<componentsDir>/<StudlyKind>.tsx`
 * exporting `<StudlyKind>`. A registered block without that file is an error,
 * not a warning: the import would not resolve, and leaving the kind out would
 * render nothing on the site without a trace.
 */
final class RegistryEmitter
{
    /**
     * @param  list<Block>  $blocks  in registry order
     * @param  string  $propsModule  import specifier of blocks.generated.ts, relative to the registry file
     * @param  string  $componentsImport  import prefix of the component folder, relative to the registry file (`./blocks`)
     * @param  string  $componentsDir  the same folder on disk, for the existence check
     */
    public function emit(array $blocks, string $propsModule, string $componentsImport, string $componentsDir): string
    {
        $entries = array_map(fn (Block $block): array => $this->entry($block, $componentsDir), $blocks);
        $this->assertDistinctIdentifiers($entries);

        $lines = ['// generated by `php artisan cms:blocks:types` — do not edit'];
        foreach ($entries as $entry) {
            $lines[] = 'import { ' . $entry['component'] . ' } from ' . json_encode($componentsImport . '/' . $entry['component'], JSON_THROW_ON_ERROR | JSON_UNESCAPED_SLASHES) . ';';
        }
        // After the component imports: `./blocks/X` sorts before `./blocks.generated` under import/order.
        $lines[] = 'import { blockProps } from ' . json_encode($propsModule, JSON_THROW_ON_ERROR | JSON_UNESCAPED_SLASHES) . ';';

        array_push(
            $lines,
            '',
            '/** Catalog entry per block kind: the zod props and the editor description. Spread into defineCatalog()\'s components. */',
            'export const blockCatalog = {',
        );
        foreach ($entries as $entry) {
            $description = $entry['description'] === null ? '' : ', description: ' . json_encode($entry['description'], JSON_THROW_ON_ERROR | JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
            $lines[] = '    ' . $entry['key'] . ': { props: blockProps' . $entry['propsAccess'] . $description . ' },';
        }

        array_push(
            $lines,
            '} as const;',
            '',
            '/** Component per block kind, found by convention at ' . $componentsImport . '/<Kind>.tsx exporting <Kind>. Spread into defineRegistry()\'s components. */',
            'export const blockComponents = {',
        );
        foreach ($entries as $entry) {
            $lines[] = '    ' . $entry['key'] . ($entry['key'] === $entry['component'] ? '' : ': ' . $entry['component']) . ',';
        }
        $lines[] = '} as const;';
        $lines[] = '';

        return implode("\n", $lines);
    }

    /** @return array{kind: string, key: string, propsAccess: string, component: string, description: string|null} */
    private function entry(Block $block, string $componentsDir): array
    {
        $kind = $block->kind();
        $component = self::componentName($kind);
        if (! is_file("{$componentsDir}/{$component}.tsx") && ! is_file("{$componentsDir}/{$component}.jsx")) {
            throw new RuntimeException("Block [{$kind}] has no component: expected {$componentsDir}/{$component}.tsx exporting `{$component}`.");
        }

        $key = EmitterNames::objectKey($kind);

        return [
            'kind' => $kind,
            'key' => $key,
            'propsAccess' => $key === $kind ? ".{$kind}" : "[{$key}]",
            'component' => $component,
            'description' => $block->description(),
        ];
    }

    public static function componentName(string $kind): string
    {
        $name = (string) preg_replace('/[^A-Za-z0-9_$]/', '', Str::studly($kind));

        return preg_match('/^[0-9]/', $name) === 1 ? "_{$name}" : $name;
    }

    /**
     * Kinds that studly-case to the same identifier ("hero" and "Hero") would
     * import one component twice under one name.
     *
     * @param  list<array{kind: string, component: string}>  $entries
     */
    private function assertDistinctIdentifiers(array $entries): void
    {
        $seen = [];
        foreach ($entries as $entry) {
            if (isset($seen[$entry['component']])) {
                throw new RuntimeException("Blocks [{$seen[$entry['component']]}] and [{$entry['kind']}] both map to component `{$entry['component']}`.");
            }
            $seen[$entry['component']] = $entry['kind'];
        }
    }
}
