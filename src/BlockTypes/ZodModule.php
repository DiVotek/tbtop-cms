<?php

declare(strict_types=1);

namespace Tbtop\Cms\BlockTypes;

use PHPStan\PhpDocParser\Ast\Type\TypeNode;
use RuntimeException;

/**
 * What every generated zod file shares, whichever emitter writes it: the
 * header, the empty-array helper (only when a fragment calls it) and the
 * `@phpstan-type` alias consts in dependency order. Each file is its own
 * module, so each one repeats the aliases it uses.
 */
final class ZodModule
{
    /**
     * @param  list<string>  $fragments  every zod fragment the file will print
     * @return list<string>
     */
    public static function header(array $fragments): array
    {
        $lines = [
            '// generated by `php artisan cms:blocks:types` — do not edit',
            'import { z } from "zod";',
            '',
        ];

        $call = ZodConverter::EMPTY_ARRAY_AS_OBJECT . '(';
        if (array_any($fragments, static fn (string $fragment): bool => str_contains($fragment, $call))) {
            $lines[] = '// PHP encodes an empty array as [], never {}: a schema whose value may be empty accepts it as {}.';
            $lines[] = 'const ' . ZodConverter::EMPTY_ARRAY_AS_OBJECT . ' = <T extends z.ZodType>(schema: T) => z.preprocess((value) => (Array.isArray(value) && value.length === 0 ? {} : value), schema);';
            $lines[] = '';
        }

        return $lines;
    }

    /** @return list<string> */
    public static function aliasConstAndType(string $name, string $fragment): array
    {
        $const = EmitterNames::aliasConst($name);

        return [
            'export const ' . $const . ' = ' . ZodFragmentFormatter::format($fragment, 0) . ';',
            'export type ' . EmitterNames::propsType($name) . " = z.infer<typeof {$const}>;",
        ];
    }

    /**
     * Post-order DFS: a dependency's entry lands in the result (and so in
     * emission order) before its dependent's, so TS never sees a `const`
     * reference an identifier declared later in the file.
     *
     * @param  list<array<string, true>>  $used  alias names each emitted shape references, in emission order
     * @param  array<string, TypeNode>  $aliases  every alias reachable from any shape, name => type
     * @return array<string, string> alias name => its own zod fragment
     */
    public static function aliasFragments(array $used, array $aliases): array
    {
        $fragments = [];
        $visiting = [];

        foreach ($used as $names) {
            foreach (array_keys($names) as $name) {
                self::emitAliasAndDependencies($name, $aliases, $fragments, $visiting);
            }
        }

        return $fragments;
    }

    /**
     * @param  array<string, TypeNode>  $aliases
     * @param  array<string, string>  $fragments
     * @param  array<string, true>  $visiting  cycle guard, cleared on return
     */
    private static function emitAliasAndDependencies(string $name, array $aliases, array &$fragments, array &$visiting): void
    {
        if (isset($fragments[$name])) {
            return;
        }

        if (isset($visiting[$name])) {
            $chain = implode(' -> ', [...array_keys($visiting), $name]);

            throw new RuntimeException("Type alias [{$name}] refers to itself ({$chain}); a recursive schema cannot be emitted as a plain const.");
        }

        $visiting[$name] = true;

        $converter = new ZodConverter($aliases);
        $fragment = $converter->convert($aliases[$name], "@phpstan-type {$name}");

        foreach (array_keys($converter->usedAliases()) as $dependency) {
            self::emitAliasAndDependencies($dependency, $aliases, $fragments, $visiting);
        }

        unset($visiting[$name]);
        $fragments[$name] = $fragment;
    }
}
