<?php

declare(strict_types=1);

use Tbtop\Cms\Block\BlockRegistry;
use Tbtop\Cms\Tests\Fixtures\BlockTypes\DashKindBlock;
use Tbtop\Cms\Tests\Fixtures\BlockTypes\NoIdentifierKindBlock;
use Tbtop\Cms\Tests\Fixtures\ConcertTicketBlock;
use Tbtop\Cms\Tests\Fixtures\Discovery\AlphaBlock;
use Tbtop\Cms\Tests\Fixtures\Discovery\BetaBlock;
use Tbtop\Cms\Tests\Fixtures\FieldsOnlyBlock;

beforeEach(function (): void {
    $this->dir = sys_get_temp_dir() . '/tbtop-cms-registry-test-' . uniqid();
    mkdir($this->dir . '/blocks', 0777, true);
    $this->typesPath = $this->dir . '/blocks.generated.ts';
    $this->registryPath = $this->dir . '/registry.generated.ts';
    config()->set('tbtop-cms.blocks.types', []);
    // Page types have their own test; this one removes the folder file by file.
    config()->set('tbtop-cms.pages.types_path', false);
});

afterEach(function (): void {
    foreach (glob($this->dir . '/blocks/*') ?: [] as $file) {
        unlink($file);
    }
    foreach ([$this->typesPath, $this->registryPath] as $file) {
        if (is_file($file)) {
            unlink($file);
        }
    }
    rmdir($this->dir . '/blocks');
    rmdir($this->dir);
});

it('writes the catalog entries and the component map next to the types file', function (): void {
    BlockRegistry::extend(fn (): array => [BetaBlock::class, DashKindBlock::class]);
    touch($this->dir . '/blocks/Beta.tsx');
    touch($this->dir . '/blocks/HeroBanner.tsx');

    $this->artisan('cms:blocks:types', ['--path' => $this->typesPath])->assertExitCode(0);

    expect(file_get_contents($this->registryPath))->toBe(<<<'TS'
        // generated by `php artisan cms:blocks:types` — do not edit
        import { Beta } from "./blocks/Beta";
        import { HeroBanner } from "./blocks/HeroBanner";
        import { blockProps } from "./blocks.generated";

        /** Catalog entry per block kind: the zod props and the editor description. Spread into defineCatalog()'s components. */
        export const blockCatalog = {
            Beta: { props: blockProps.Beta, description: "A \"quoted\" fixture block" },
            "hero-banner": { props: blockProps["hero-banner"] },
        } as const;

        /** Component per block kind, found by convention at ./blocks/<Kind>.tsx exporting <Kind>. Spread into defineRegistry()'s components. */
        export const blockComponents = {
            Beta,
            "hero-banner": HeroBanner,
        } as const;

        TS);
});

it('fails without writing anything when a registered block has no component file', function (): void {
    BlockRegistry::extend(fn (): array => [AlphaBlock::class, BetaBlock::class]);
    touch($this->dir . '/blocks/Alpha.tsx');

    $this->artisan('cms:blocks:types', ['--path' => $this->typesPath])
        ->expectsOutputToContain('Block [Beta] has no component')
        ->assertExitCode(1);

    expect(is_file($this->typesPath))->toBeFalse()
        ->and(is_file($this->registryPath))->toBeFalse();
});

it('skips the registry when the host has no component folder', function (): void {
    rmdir($this->dir . '/blocks');
    BlockRegistry::extend(fn (): array => [BetaBlock::class]);

    $this->artisan('cms:blocks:types', ['--path' => $this->typesPath])->assertExitCode(0);

    expect(is_file($this->typesPath))->toBeTrue()
        ->and(is_file($this->registryPath))->toBeFalse();
    mkdir($this->dir . '/blocks');
});

it('writes a registry configured in another folder, importing the types file by its relative path', function (): void {
    config()->set('tbtop-cms.blocks.registry_path', $this->dir . '/generated/registry.ts');
    config()->set('tbtop-cms.blocks.components_dir', '../blocks');
    BlockRegistry::extend(fn (): array => [BetaBlock::class]);
    touch($this->dir . '/blocks/Beta.tsx');

    $this->artisan('cms:blocks:types', ['--path' => $this->typesPath])->assertExitCode(0);

    expect(file_get_contents($this->dir . '/generated/registry.ts'))
        ->toContain('import { Beta } from "../blocks/Beta";')
        ->toContain('import { blockProps } from "../blocks.generated";');
    unlink($this->dir . '/generated/registry.ts');
    rmdir($this->dir . '/generated');
});

it('resolves a relative --path against the working directory when the registry path is absolute', function (): void {
    config()->set('tbtop-cms.blocks.registry_path', $this->dir . '/registry.generated.ts');
    BlockRegistry::extend(fn (): array => [BetaBlock::class]);
    touch($this->dir . '/blocks/Beta.tsx');
    $cwd = getcwd();
    chdir($this->dir);

    try {
        $this->artisan('cms:blocks:types', ['--path' => 'blocks.generated.ts'])->assertExitCode(0);
    } finally {
        chdir((string) $cwd);
    }

    expect(file_get_contents($this->registryPath))->toContain('import { blockProps } from "./blocks.generated";');
});

it('fails when a kind has no characters usable as a component name', function (): void {
    BlockRegistry::extend(fn (): array => [NoIdentifierKindBlock::class]);

    $this->artisan('cms:blocks:types', ['--path' => $this->typesPath])
        ->expectsOutputToContain('Block [--] cannot be mapped to a component name')
        ->assertExitCode(1);

    expect(is_file($this->registryPath))->toBeFalse();
});

it('imports components relatively when components_dir is given without a leading dot', function (): void {
    config()->set('tbtop-cms.blocks.components_dir', 'blocks');
    BlockRegistry::extend(fn (): array => [BetaBlock::class]);
    touch($this->dir . '/blocks/Beta.tsx');

    $this->artisan('cms:blocks:types', ['--path' => $this->typesPath])->assertExitCode(0);

    expect(file_get_contents($this->registryPath))->toContain('import { Beta } from "./blocks/Beta";');
});

it('reports a stale registry under --check even when the types file is current', function (): void {
    BlockRegistry::extend(fn (): array => [BetaBlock::class]);
    touch($this->dir . '/blocks/Beta.tsx');
    $this->artisan('cms:blocks:types', ['--path' => $this->typesPath])->assertExitCode(0);
    file_put_contents($this->registryPath, "// stale\n");

    $this->artisan('cms:blocks:types', ['--check' => true, '--path' => $this->typesPath])->assertExitCode(1);

    expect(file_get_contents($this->registryPath))->toBe("// stale\n");
});

it('asks no component of a block placeable nowhere, and one of every other block, a subtype-only one included', function (): void {
    BlockRegistry::extend(fn (): array => [AlphaBlock::class, FieldsOnlyBlock::class, ConcertTicketBlock::class]);
    touch($this->dir . '/blocks/Alpha.tsx');

    $this->artisan('cms:blocks:types', ['--path' => $this->typesPath])
        ->expectsOutputToContain('Block [ConcertTicket] has no component')
        ->assertExitCode(1);

    touch($this->dir . '/blocks/ConcertTicket.tsx');
    $this->artisan('cms:blocks:types', ['--path' => $this->typesPath])->assertExitCode(0);

    expect(file_get_contents($this->registryPath))->toContain('import { Alpha }')
        ->toContain('import { ConcertTicket }')
        ->not->toContain('FieldsOnly');
});

it('writes no registry when registry_path is false, even with a components folder', function (): void {
    config()->set('tbtop-cms.blocks.registry_path', false);
    BlockRegistry::extend(fn (): array => [AlphaBlock::class]);

    $this->artisan('cms:blocks:types', ['--path' => $this->typesPath])->assertExitCode(0);

    expect(is_file($this->typesPath))->toBeTrue()
        ->and(is_file($this->registryPath))->toBeFalse();
});
