<?php

declare(strict_types=1);

use Tbtop\Cms\Block\BlockRegistry;
use Tbtop\Cms\Block\Blocks\ContactForm;
use Tbtop\Cms\Block\Blocks\HeroBlock;
use Tbtop\Cms\Tests\Fixtures\BlockTypes\AliasConflictOneBlock;
use Tbtop\Cms\Tests\Fixtures\BlockTypes\AliasConflictTwoBlock;
use Tbtop\Cms\Tests\Fixtures\BlockTypes\TypedAliasBlock;
use Tbtop\Cms\Tests\Fixtures\BlockTypes\TypedFormBlock;
use Tbtop\Cms\Tests\Fixtures\BlockTypes\UnsupportedShapeBlock;
use Tbtop\Cms\Tests\Fixtures\BlockTypes\UntypedBlock;

beforeEach(function (): void {
    $this->outputPath = sys_get_temp_dir() . '/tbtop-cms-blocks-types-test-' . uniqid() . '.ts';
});

afterEach(function (): void {
    if (is_file($this->outputPath)) {
        unlink($this->outputPath);
    }
});

it('writes typed props, an alias export, and the blockProps map for the real package registry', function (): void {
    config()->set('tbtop-cms.blocks.types', []);
    BlockRegistry::extend(fn (): array => [HeroBlock::class, ContactForm::class]);

    $this->artisan('cms:blocks:types', ['--path' => $this->outputPath])->assertExitCode(0);

    $contents = file_get_contents($this->outputPath);

    expect($contents)->toContain('// generated by `php artisan cms:blocks:types` — do not edit')
        ->toContain('import { z } from "zod";')
        ->toContain('export const heroProps = z.object({')
        ->toContain('export type HeroProps = z.infer<typeof heroProps>;')
        ->toContain('export const contactFormProps')
        ->toContain('action: z.string(),')
        ->toContain('honeypotField: z.string().optional(),')
        ->toContain('Hero: heroProps,')
        ->toContain('ContactForm: contactFormProps,');
});

it('emits an alias export referenced by its emitted const name', function (): void {
    config()->set('tbtop-cms.blocks.types', []);
    BlockRegistry::extend(fn (): array => [TypedAliasBlock::class]);

    $this->artisan('cms:blocks:types', ['--path' => $this->outputPath])->assertExitCode(0);

    $contents = file_get_contents($this->outputPath);

    expect($contents)->toContain('export const ctaLinkProps = z.object({')
        ->toContain('export type CtaLinkProps = z.infer<typeof ctaLinkProps>;')
        ->toContain('cta: ctaLinkProps,');
});

it('degrades an untyped block to the z.record fallback with a TODO comment and a warning, still exiting 0', function (): void {
    config()->set('tbtop-cms.blocks.types', []);
    BlockRegistry::extend(fn (): array => [UntypedBlock::class]);

    $this->artisan('cms:blocks:types', ['--path' => $this->outputPath])
        ->expectsOutputToContain('[Untyped] has no typed @return array{...}')
        ->assertExitCode(0);

    $contents = file_get_contents($this->outputPath);

    expect($contents)->toContain('export const untypedProps = z.record(z.string(), z.unknown()); // TODO: add @return array{...} to Untyped::resolve()');
});

it('appends action/honeypotField to a HandlesFormSubmission block after its docblock keys', function (): void {
    config()->set('tbtop-cms.blocks.types', []);
    BlockRegistry::extend(fn (): array => [TypedFormBlock::class]);

    $this->artisan('cms:blocks:types', ['--path' => $this->outputPath])->assertExitCode(0);

    $contents = file_get_contents($this->outputPath);

    expect($contents)->toContain('heading: z.string(),')
        ->toContain('action: z.string(),')
        ->toContain('honeypotField: z.string().optional(),');
});

it('errors with exit 1 and writes nothing when two blocks declare the same alias name with different shapes', function (): void {
    config()->set('tbtop-cms.blocks.types', []);
    BlockRegistry::extend(fn (): array => [AliasConflictOneBlock::class, AliasConflictTwoBlock::class]);

    $this->artisan('cms:blocks:types', ['--path' => $this->outputPath])
        ->expectsOutputToContain('Type alias [Shared] is declared with two different shapes')
        ->assertExitCode(1);

    expect(is_file($this->outputPath))->toBeFalse();
});

it('errors with exit 1 naming the block and key path for an unsupported nested construct', function (): void {
    config()->set('tbtop-cms.blocks.types', []);
    BlockRegistry::extend(fn (): array => [UnsupportedShapeBlock::class]);

    $this->artisan('cms:blocks:types', ['--path' => $this->outputPath])
        ->expectsOutputToContain('Block [UnsupportedShape]: unsupported PHPDoc construct at [handle]: resource')
        ->assertExitCode(1);

    expect(is_file($this->outputPath))->toBeFalse();
});
