        ->toContain("extra: emptyArrayAsObject(z.object({\n        note: z.string().optional(),\n    })),")
        ->toContain("export const optionalOnlyRootProps = emptyArrayAsObject(z.object({\n    title: z.string().optional(),\n}));");
});

